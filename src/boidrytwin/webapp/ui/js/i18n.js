export function columnLabel(column) {
  const heater = /^(gas|oil)_temperature_after_heater_(\d+)$/.exec(column);
  if (heater) {
    const what = heater[1] === "gas" ? ["Gas nach Erhitzer", "Gas after heater"] : ["Öl nach Erhitzer", "Oil after heater"];
    return `${pick(what)} ${heater[2]}`;
  }
  return from(COLUMNS, column, column.replace(/_/g, " "));
}
