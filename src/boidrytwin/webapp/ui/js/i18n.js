export function lang() {
  return getState().lang;
}

function pick(pair) {
  return pair[lang() === "en" ? 1 : 0] || pair[0];
}

export function t(key, vars = {}) {
  const pair = TEXTS[key];
  if (!pair) return key;
  return pick(pair).replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}

function from(table, key, fallback) {
  return table[key] ? pick(table[key]) : fallback;
}

// "boiler_house.heaters[2]" -> "Kesselhaus: Thermoölerhitzer 2"
export function sectionLabel(name) {
  const match = /^(.*)\[(\d+)\]$/.exec(name);
  const path = match ? match[1] : name;
  const label = from(SECTIONS, path, path);
  return match ? `${label} ${match[2]}` : label;
}

